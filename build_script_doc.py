def main():
    doc = Document()

    # 既定フォント
    style = doc.styles['Normal']
    style.font.name = 'Yu Gothic'
    style.font.size = Pt(11)

    # タイトル
    title = doc.add_heading('発表原稿', level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub = doc.add_paragraph('山火事から守る熱活性化シリカエアロゲル（Dong et al., Adv. Mater. 2024）')
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for r in sub.runs:
        r.font.size = Pt(12)
        r.font.color.rgb = RGBColor(0x55, 0x66, 0x77)
    doc.add_paragraph()

    for label, slide_title, lines in SCRIPT:
        h = doc.add_heading(f'{label}　{slide_title}', level=1)
        for r in h.runs:
            r.font.color.rgb = RGBColor(0x1e, 0x29, 0x3b)
        for line in lines:
            p = doc.add_paragraph(line)
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.line_spacing = 1.4

    out = '/home/user/my-first-claude/発表原稿.docx'
    doc.save(out)
    print(f'完了: {out}')


if __name__ == '__main__':
    main()
